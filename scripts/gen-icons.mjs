import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ph = require('@iconify-json/ph/icons.json');
const mapPath = path.resolve('scripts/icon-map.json');
const outPath = path.resolve('src/lib/icons.ts');

const iconMap = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
const entries = {};

for (const [key, phName] of Object.entries(iconMap)) {
  const icon = ph.icons[phName];
  if (!icon) {
    throw new Error(`Missing Phosphor icon: ${phName} (mapped from ${key})`);
  }
  entries[key] = icon.body;
}

const code = `// Auto-generated by scripts/gen-icons.mjs. Do not edit by hand.
export const ICONS = ${JSON.stringify(entries, null, 2)} as const;

export type IconName = keyof typeof ICONS;
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, code, 'utf8');
console.log(`Generated ${Object.keys(entries).length} icons -> src/lib/icons.ts`);
